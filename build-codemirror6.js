#!/usr/bin/env node
"use strict"

const fs = require("fs")
const path = require("path")
const esbuild = require("esbuild")

const root = __dirname
const packageJson = require("./package.json")
const runtimePackages = [
  "@codemirror/autocomplete",
  "@codemirror/commands",
  "@codemirror/language",
  "@codemirror/search",
  "@codemirror/state",
  "@codemirror/view",
  "@lezer/common",
  "@lezer/highlight"
]
const packageVersions = Object.fromEntries(runtimePackages.map(name => [
  name,
  packageJson.dependencies[name]
]))
const bundlePath = path.join(
  root,
  "src/js/codemirror6/runtime/dist/codemirror6-runtime.js"
)
const mapPath = bundlePath + ".map"
const check = process.argv.includes("--check")

function normalizeJavaScript(contents) {
  return Buffer.from(Buffer.from(contents).toString("utf8").replace(/[ \t]+$/gm, ""))
}

async function build() {
  const result = await esbuild.build({
    absWorkingDir: root,
    entryPoints: ["src/js/codemirror6/runtime/source/index.js"],
    bundle: true,
    format: "iife",
    platform: "browser",
    target: ["chrome110", "firefox110", "safari16", "edge110"],
    minify: true,
    sourcemap: "linked",
    sourcesContent: true,
    outfile: "src/js/codemirror6/runtime/dist/codemirror6-runtime.js",
    write: false,
    legalComments: "eof",
    banner: {js: "/*! GENERATED by npm run build:codemirror — DO NOT EDIT. */"},
    define: {
      __PUZZLESCRIPT_CM6_VERSIONS__: JSON.stringify(packageVersions)
    }
  })
  const js = normalizeJavaScript(result.outputFiles.find(file => file.path === bundlePath).contents)
  const map = result.outputFiles.find(file => file.path === mapPath).contents
  if (check) {
    if (!fs.existsSync(bundlePath) || !fs.existsSync(mapPath) ||
        !fs.readFileSync(bundlePath).equals(js) || !fs.readFileSync(mapPath).equals(map)) {
      throw new Error("CodeMirror bundle is stale; run npm run build:codemirror")
    }
  } else {
    fs.writeFileSync(bundlePath, js)
    fs.writeFileSync(mapPath, map)
  }
}

build().catch(error => {
  console.error(error.message || error)
  process.exitCode = 1
})
