import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export async function buildMisOptimizer() {
  // Workers use the optimizer; the page uses the smaller source-tools bundle;
  // the Static analysis tab's worker uses the analysis bundle.
  for (const [name, globalName] of [['optimizer', 'MISOptimizer'], ['tools', 'MISTools'], ['analysis', 'MISAnalysis']]) {
    const result = await build({
      entryPoints: [path.join(root, `src/js/mis/mis_${name}_entry.js`)],
      bundle: true, platform: 'browser', format: 'iife', globalName,
      target: ['es2020'], minify: true, write: false,
      banner: { js: '// Generated by scripts/build-mis-optimizer.mjs; edit the shared sources.' },
    });
    const output = path.join(root, `src/js/mis/mis_${name}_bundle.js`);
    const content = result.outputFiles[0].text;
    const previous = await readFile(output, 'utf8').catch(() => '');
    if (previous !== content) await writeFile(output, content);
  }
  return path.join(root, 'src/js/mis/mis_optimizer_bundle.js');
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await buildMisOptimizer();
