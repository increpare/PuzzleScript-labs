import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export async function buildMisOptimizer() {
  const result = await build({
    entryPoints: [path.join(root, 'src/js/mis/mis_optimizer_entry.js')],
    bundle: true, platform: 'browser', format: 'iife', globalName: 'MISOptimizer',
    target: ['es2020'], minify: true, write: false,
    banner: { js: '// Generated by scripts/build-mis-optimizer.mjs; edit the shared sources.' },
  });
  const output = path.join(root, 'src/js/mis/mis_optimizer_bundle.js');
  const content = result.outputFiles[0].text;
  const previous = await readFile(output, 'utf8').catch(() => '');
  if (previous !== content) await writeFile(output, content);
  return output;
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await buildMisOptimizer();
